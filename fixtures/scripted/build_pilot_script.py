#!/usr/bin/env python3
"""Build the scripted pilot agent: the known_good reference solution, delivered over K intervals.

    python fixtures/scripted/build_pilot_script.py 60 6 > fixtures/scripted/pilot_agent.yaml

It stands in for Claude Code in the Phase 4 pipeline test and the scripted pilot (no spend). Each
interval gets one mid-interval commit, so every interval has an accepted commit, plus telemetry
(an ``api_request`` with cost and tokens) and assistant text for the judge. Interval 2 adds the
route before its test (interval 3), so the ``endpoint-needs-test`` probe fires once; later
intervals churn a notes file, so W(t) is non-zero. The output is deterministic.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
OVERLAY = HERE.parent / "snapshots" / "known_good" / "overlay"

STEPS = [
    (["app/config.py", "app/ratelimit.py"], "Add export rate-limit settings and a fixed-window limiter"),
    (["app/main.py"], "Add GET /export: paginated CSV, rate limit, audit entry"),
    (["tests/test_export.py"], "Add tests for GET /export"),
]


def _notes(k: int) -> str:
    """Notes file that grows each interval and rewrites the previous interval's last line."""
    lines = ["# Export notes", ""]
    for i in range(4, k + 1):
        lines += [f"- interval {i}: reviewed export pagination", f"- interval {i}: reviewed rate limit"]
    if k >= 5:
        lines[-3] = f"- interval {k - 1}: rate limit reviewed again (window boundary)"
    return "\n".join(lines) + "\n"


def _assistant(text: str) -> dict:
    return {"type": "assistant", "message": {"role": "assistant", "content": [{"type": "text", "text": text}]}}


def build(dt_s: float, k_total: int) -> dict:
    actions = []
    for k in range(1, k_total + 1):
        at = (k - 0.5) * dt_s
        if k <= len(STEPS):
            files, message = STEPS[k - 1]
            writes = [(f, (OVERLAY / f).read_text()) for f in files]
        else:
            files, message = ["NOTES.md"], f"Update export notes ({k})"
            writes = [("NOTES.md", _notes(k))]
        actions.append({"at": round(at, 3), "do": "emit_stream_event",
                        "event": _assistant(f"Interval {k}: {message}. The existing tests still pass.")})
        for i, (path, content) in enumerate(writes):
            actions.append({"at": round(at + 0.05 * (i + 1), 3), "do": "write_file", "path": path,
                            "content": content})
        actions.append({"at": round(at + 0.3, 3), "do": "git_commit", "message": message})
        actions.append({"at": round(at + 0.35, 3), "do": "emit_otel", "event": "claude_code.api_request",
                        "attrs": {"cost_usd": "0.05", "input_tokens": "1200", "output_tokens": "300",
                                  "cache_read_tokens": "8000", "cache_creation_tokens": "0",
                                  "model": "scripted", "session.id": "scripted-session"}})
    return {"idle_s": 0.2, "actions": actions}


def main(argv: list[str]) -> int:
    dt_s, k_total = float(argv[1]), int(argv[2])
    sys.stdout.write("# Generated by fixtures/scripted/build_pilot_script.py "
                     f"{argv[1]} {argv[2]}; do not edit.\n")
    yaml.safe_dump(build(dt_s, k_total), sys.stdout, sort_keys=False, width=100)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
